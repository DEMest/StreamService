/**
 * Как одного спортсмена узнают в разных турнирах организации.
 *
 * Пока у участников нет своих аккаунтов, спортсмен — строка `Athlete` уровня
 * организации, и схватки разных турниров сходятся на одну страницу спортсмена
 * только если каждый раз находится та же строка. Находит её
 * `@@unique([orgId, identityKey])`, а ключ считает эта функция — и только она:
 * второй способ собрать ключ (в SQL, в сиде, в импорте из таблицы) рано или
 * поздно разойдётся с этим и заведёт человеку вторую страницу.
 *
 * Правило: фамилия, имя, год рождения и школа должны совпасть. Не различается
 * то, чем один и тот же человек отличается в списках, которые организаторы
 * грузят из таблиц: регистр, пробелы, «ё»/«е», кавычки, вид тире и пробелы
 * вокруг дефиса, пробел после «№», невидимые символы.
 *
 * Год и школа участвуют в ключе, даже когда не указаны: «Иванов Иван» без
 * школы и «Иванов Иван» из «Барса» — два разных спортсмена. Склеить
 * однофамильцев хуже, чем завести одному человеку две страницы: чужие схватки
 * на странице ребёнка заметят сразу, а дубль объединяется руками. По той же
 * причине латинские буквы-двойники («Иванoв» с латинской «o») не приводятся
 * к кириллице: такая замена склеила бы и настоящие иностранные фамилии.
 *
 * Полные тёзки одного года из одной школы этим ключом не различаются.
 *
 * Менять правило можно только вместе с пересчётом `identityKey` у уже
 * заведённых строк (data-скрипт в `prisma/data/`).
 */
export interface AthleteIdentity {
  lastName: string;
  firstName: string;
  birthYear?: number | null;
  school?: string | null;
}

const SEPARATOR = '|';

/** Нулевой ширины и мягкий перенос: приезжают при копировании из таблиц и сайтов. */
const INVISIBLE = /[\u200B-\u200D\uFEFF\u00AD]/g;
/** Все виды дефисов и тире, которыми набирают двойные фамилии. */
const DASHES = /[\u2010-\u2015\u2212]/g;
const QUOTES = /[«»"“”„‟'‘’`]/g;

function normalize(value: string | null | undefined): string {
  return (value ?? '')
    .normalize('NFC')
    .replace(INVISIBLE, '')
    .toLocaleLowerCase('ru-RU')
    .replace(/ё/g, 'е')
    .replace(QUOTES, '')
    .replace(DASHES, '-')
    // Разделитель внутри значения склеил бы «a|b» + «c» с «a» + «b|c».
    .split(SEPARATOR)
    .join(' ')
    .replace(/\s*-\s*/g, '-')
    .replace(/№\s+/g, '№')
    .replace(/\s+/g, ' ')
    .trim();
}

export function athleteIdentityKey(athlete: AthleteIdentity): string {
  const lastName = normalize(athlete.lastName);
  if (!lastName) {
    // Без фамилии ключ у всех одинаковый: безымянные спортсмены организации
    // схлопнулись бы в одну строку со всеми схватками друг друга.
    throw new Error('athleteIdentityKey: у спортсмена нет фамилии');
  }
  return [
    lastName,
    normalize(athlete.firstName),
    athlete.birthYear == null ? '' : String(athlete.birthYear),
    normalize(athlete.school),
  ].join(SEPARATOR);
}
