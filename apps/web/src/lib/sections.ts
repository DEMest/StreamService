/**
 * Кому принадлежит закрытый раздел сайта. Один список на три места, которые
 * иначе разъезжаются молча: гвард в `middleware.ts`, редирект после входа в
 * `app/login/page.tsx` и главная кнопка шапки в `components/Header.tsx`.
 *
 * Разъезд тут не падает, а тихо портит вход: если login отправит человека в
 * раздел, который middleware для его роли не признаёт, тот немедленно
 * развернёт его обратно — и получится редирект по кругу вместо кабинета.
 *
 * Дублирует `@Roles(...)` на бэкенде намеренно: гвард вернёт 403 на запросы к
 * API, но страницу это не остановит — админ организации до сих пор мог открыть
 * /admin и смотреть на пустой каркас, который сыплет 403 в консоль. Роль
 * решается здесь, до рендера.
 *
 * Порядок массива задаёт приоритет поиска префикса: `/admin/ads` обязан стоять
 * раньше `/admin`, иначе рекламный менеджер упрётся в правило раздела
 * организаций, куда ему нельзя.
 *
 * `home` помечает, чей это раздел по умолчанию. Вычислить дом из одних `roles`
 * не выйдет — у /admin/ads их две, и обе имеют на раздел полное право.
 */
export interface Section {
  path: string;
  roles: string[];
  home: string;
}

export const SECTIONS: Section[] = [
  { path: '/admin/ads', roles: ['superadmin', 'ad_manager'], home: 'ad_manager' },
  { path: '/admin', roles: ['superadmin'], home: 'superadmin' },
  { path: '/dashboard', roles: ['org_admin'], home: 'org_admin' },
];

export function sectionFor(pathname: string): Section | null {
  return SECTIONS.find((s) => pathname.startsWith(s.path)) ?? null;
}

/**
 * Раздел роли — куда вести после входа и куда возвращать из чужого раздела.
 *
 * Хост при этом не важен, топологию знает конфиг nginx, а не приложение. У
 * суперадмина на основном домене `/admin` встретит редирект на admin.<домен>;
 * у организации, забредшей на поддомен, `/dashboard` — редирект обратно, где
 * её host-only cookie нет, и попросят войти. Оба пути длиннее одного перехода,
 * но приводят человека туда, где его раздел действительно работает.
 *
 * Неизвестная роль получает «/» — публичную главную, а не чей-то кабинет.
 */
export function homeForRole(role: string): string {
  return SECTIONS.find((s) => s.home === role)?.path ?? '/';
}
